#A tuple is an immutable data type in python # Tuple is just like string
a = (1, 2, 5, 6, "Harry", "prince")
print(type(a))

b = ()      #Empty tuple
print(type(b))

c = (1)     #It is consider as a "Integer"
print(type(c))

d = (1,)    # if we add , after 1 it will consider it as a tuple
print(type(d))



