"""We can provide a skip value as a part of our slice like this"""

word = "amazing"

print(word[1: 6: 2]) #"mzn" #It means execute from 1 to 5 and then take jump of two variables
                     #इसका मतलब है 1 से 5 तक निष्पादित करें और फिर दो वेरिएबल्स में लगातार छलांग लगाएं

alphabet = "abcdefghijkmnopqrstuvwxyz"

print(alphabet[0: 26: 3]) #Execute from 1 to 25 alphabet and then take jumps after every 3 alphabet
