"""Always convert negative into positive"""
name = "harry"

print(name[0:3])

print(name[-4:-1])  #convert negative indices into positive indices
print(name[1:4])            
print()

print(name[:5])     #is same as print(name[:5])
print(name[0:5])

print(name[1:])     #is same as print(name[1:5])
print(name[1:5])